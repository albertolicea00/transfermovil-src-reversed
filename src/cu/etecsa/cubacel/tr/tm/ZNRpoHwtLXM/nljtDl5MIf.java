    private void updateOperation(Operacion operacion) {
        try {
            Operacion original = unYp8VQThY.getInstance().getOperacion(operacion.getOperacion());
            if (original != null) {
                if (unYp8VQThY.getInstance().getCountOperacion(operacion.getOperacion()) > 1) {
                    for (Operacion uyh0pxs9m37in : unYp8VQThY.getInstance().getListOperacion(operacion.getOperacion())) {
                        unYp8VQThY.getInstance().deleteOperacion(uyh0pxs9m37in);
                    }
                    unYp8VQThY.getInstance().addOperacion(operacion);
                    return;
                }
                original.setFragment_name(operacion.getFragment_name());
                original.setImagen(operacion.getImagen());
                original.setTitulo(operacion.getTitulo());
                original.setSubtitulo(operacion.getSubtitulo());
                unYp8VQThY.getInstance().updateOperacion(original);
                return;
            }
            unYp8VQThY.getInstance().addOperacion(operacion);
        } catch (Exception ex) {
            try {
                unYp8VQThY.getInstance().deleteOperacion(unYp8VQThY.getInstance().getOperacion(operacion.getOperacion()));
                unYp8VQThY.getInstance().addOperacion(operacion);
            } catch (Exception e) {
                Log.e("OPERLOG", ex.getMessage());
            }
        }
    }

